-- tools/export_web_data.lua
-- Single source of truth: the website reads the SAME world + quest data as
-- the addon. Writes docs/assets/data.js and tests/fixtures/parity.json
-- (Lua ATLAS results the JavaScript port must reproduce exactly).
--   lua5.1 tools/export_web_data.lua
package.path = "tests/?.lua;" .. package.path
local ns = require("loader").load()
local W, Q = ns.WorldData, ns.QuestData

local function json(v, indent)
    local t = type(v)
    if t == "nil" then return "null"
    elseif t == "boolean" then return tostring(v)
    elseif t == "number" then
        if v == math.floor(v) and math.abs(v) < 1e15 then return string.format("%d", v) end
        return string.format("%.17g", v)
    elseif t == "string" then
        return '"' .. v:gsub('\\', '\\\\'):gsub('"', '\\"'):gsub("\n", "\\n") .. '"'
    end
    local isArray = (#v > 0) or next(v) == nil
    local parts = {}
    if isArray then
        for i = 1, #v do parts[i] = json(v[i]) end
        return "[" .. table.concat(parts, ",") .. "]"
    end
    local keys = {}
    for k in pairs(v) do keys[#keys + 1] = tostring(k) end
    table.sort(keys)
    for _, k in ipairs(keys) do
        local value = v[k]; if value == nil then value = v[tonumber(k)] end
        parts[#parts + 1] = json(k) .. ":" .. json(value)
    end
    return "{" .. table.concat(parts, ",") .. "}"
end

local locations = {}
for _, id in ipairs(W.locationOrder) do locations[#locations + 1] = W.locations[id] end

local data = {
    yardsPerUnit = W.YARDS_PER_UNIT,
    locations = locations,
    flights = W.flights,
    transports = W.transports,
    teleports = W.teleports,
    roads = W.roads,
    modeLabels = W.modeLabels,
    quests = Q.list,
    constants = {
        walkNeighbours = ns.WorldGraphBuilder.WALK_NEIGHBOURS,
        roadFactor = ns.TravelLinks.Walk.ROAD_FACTOR,
        flightSpeed = ns.TravelLinks.Flight.SPEED,
        flightCurve = ns.TravelLinks.Flight.CURVE_FACTOR,
        boarding = ns.TravelLinks.Flight.BOARDING,
        hearthPenalty = ns.TravelLinks.Hearthstone.RESERVE_PENALTY,
        solver = ns.AtlasSolver.DEFAULTS,
        riding = ns.AtlasQuestRouter.RIDING,
    },
}
local f = assert(io.open("docs/assets/data.js", "w"))
f:write("// Generated by tools/export_web_data.lua from the addon's Lua data. Do not edit.\n")
f:write("window.AQR_DATA = " .. json(data) .. ";\n")
f:close()

-- parity scenarios -------------------------------------------------------
local scenarios = {
    { faction = "Alliance", class = "WARRIOR", start = "stormwind", bind = "stormwind", speed = 7, quests = { 1001, 1002, 1003, 1004, 1005, 1006 } },
    { faction = "Alliance", class = "MAGE", start = "ironforge", bind = "ironforge", speed = 14, quests = { 1007, 1008, 1009, 1010, 1011, 1012, 1013 } },
    { faction = "Horde", class = "SHAMAN", start = "orgrimmar", bind = "orgrimmar", speed = 11.2, quests = { 3001, 3002, 3003, 3004, 3005, 3012 } },
    { faction = "Horde", class = "DRUID", start = "undercity", bind = "undercity", speed = 7, quests = { 3006, 3007, 3008, 3009, 3010, 2003, 1010 } },
    { faction = "Alliance", class = "PRIEST", start = "gadgetzan", bind = "theramore", speed = 11.2, quests = { 2001, 2002, 2004, 2005, 1013 } },
}
local planner = ns.QuestRoutePlanner.new(W)
local out = {}
for i, s in ipairs(scenarios) do
    local log = ns.QuestLog.new(ns.EventBus.new(), Q.catalog)
    for _, id in ipairs(s.quests) do log:add(id) end
    local plan = planner:plan({ faction = s.faction, class = s.class, groundSpeed = s.speed,
                                bindLocation = s.bind, cooldowns = {} }, log:all(), s.start)
    local legs = {}
    for j, leg in ipairs(plan.legs) do
        legs[j] = leg.kind == "step" and ("step:" .. leg.step:id()) or (leg.mode .. ":" .. leg.from .. ">" .. leg.to)
    end
    out[i] = { scenario = s, legs = legs, totalSeconds = math.floor(plan.totalSeconds * 1000 + 0.5) / 1000,
               iterations = plan.meta.iterations, tour = plan.meta.tour }
end
f = assert(io.open("tests/fixtures/parity.json", "w"))
f:write(json(out), "\n")
f:close()
print("wrote docs/assets/data.js and tests/fixtures/parity.json")
