--[[--------------------------------------------------------------------------
  Atlas/AtlasClassic.lua
  Line-by-line Lua port of Atlas.java (github.com/savastakan/atlas).

  It exists for one reason: to PROVE our port understands the original.
  tests/spec_atlas_classic.lua runs it on FSM files and compares the output
  with what the real Java program prints (fixtures generated by
  tools/java_reference.sh). Same input, same test suite, character for character.

  Unit weights, every edge required, "gain" = edge not yet in the path.
----------------------------------------------------------------------------]]
local _, ns = ...
local Class = ns.Class

local AtlasClassic = Class.define("AtlasClassic")

function AtlasClassic:init(ordering)
    -- Java iterates HashSet<Integer>; we reproduce that order exactly.
    self.ordering = ordering or ns.DfsOrderings.JavaHashSet.new()
end

--- Atlas.longestPath(graph, start) from the Java code.
function AtlasClassic:longestPath(graph, start)
    local path = { start }
    local inPath = function(label)
        for i = 1, #path do if path[i] == label then return true end end
        return false
    end
    while true do
        local currentStart = table.remove(path)                 -- path.removeLast()
        local order, position = ns.LocalDag.build(graph, currentStart, self.ordering)
        local cost, comeFrom = {}, {}
        cost[currentStart] = 0
        local currentCost, current = -math.huge, nil
        for i = 1, #order do                                    -- while (!stack.isEmpty())
            local edge = order[i]
            for _, neighbor in ipairs(self.ordering:order(graph:successors(edge), graph)) do
                if position[neighbor] > i then                  -- !visited[neighbor]
                    local newCost = cost[edge] + (inPath(neighbor) and 0 or 1)
                    if (cost[neighbor] or -math.huge) < newCost then
                        cost[neighbor] = newCost
                        comeFrom[neighbor] = edge
                        if currentCost < newCost then
                            currentCost = newCost
                            current = neighbor
                        end
                    end
                end
            end
        end
        if current == nil or cost[current] <= 0 then
            return path                                         -- (last edge dropped, as in Java)
        end
        local size = #path
        table.insert(path, current)
        while comeFrom[current] ~= nil do
            current = comeFrom[current]
            table.insert(path, size + 1, current)
        end
    end
end

--- Atlas.run(graph): the comma-separated input sequence (the "test suite").
function AtlasClassic:run(graph, startLabel)
    local path = self:longestPath(graph, startLabel)
    local inputs = {}
    for i = 1, #path do
        inputs[i] = tostring(graph:getEdge(path[i]).payload.input)
    end
    return table.concat(inputs, ","), path
end

ns.AtlasClassic = AtlasClassic
